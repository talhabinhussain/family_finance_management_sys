CREATE TABLE income (
    income_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id INTEGER NOT NULL REFERENCES member(member_id) ON DELETE RESTRICT,
    account_id INTEGER NOT NULL REFERENCES account(account_id) ON DELETE RESTRICT,
    category_id INTEGER NOT NULL REFERENCES category(category_id) ON DELETE RESTRICT,
    income_source_id INTEGER NOT NULL REFERENCES income_source(income_source_id) ON DELETE RESTRICT,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    transaction_date DATE NOT NULL,
    description VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE expense (
    expense_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id INTEGER NOT NULL REFERENCES member(member_id) ON DELETE RESTRICT,
    account_id INTEGER NOT NULL REFERENCES account(account_id) ON DELETE RESTRICT,
    category_id INTEGER NOT NULL REFERENCES category(category_id) ON DELETE RESTRICT,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    transaction_date DATE NOT NULL,
    description VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE bill_payment (
    bill_payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id INTEGER NOT NULL REFERENCES bill(bill_id) ON DELETE RESTRICT,
    expense_id INTEGER NOT NULL UNIQUE REFERENCES expense(expense_id) ON DELETE RESTRICT,
    period_month DATE NOT NULL CHECK (period_month = date_trunc('month', period_month)::DATE),
    paid_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (bill_id, period_month)
);

CREATE TABLE savings_contribution (
    contribution_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id INTEGER NOT NULL REFERENCES savings_goal(goal_id) ON DELETE RESTRICT,
    member_id INTEGER NOT NULL REFERENCES member(member_id) ON DELETE RESTRICT,
    account_id INTEGER NOT NULL REFERENCES account(account_id) ON DELETE RESTRICT,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    contribution_date DATE NOT NULL,
    description VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
